// Normalization function: maps both brands into shared schema
export function normalizeAccessEvent(
  rawEvent: SaltoDoorEvent | GantnerLockerEvent
): NormalizedEvent {
  if ('door_id' in rawEvent) {
    // Salto door event
    return {
      id: rawEvent.event_id,
      credential_id: rawEvent.credential_id,
      location: rawEvent.location,
      timestamp: rawEvent.timestamp,
      event_type: 'door_access',
      action: rawEvent.result === 'granted' ? 'entry_granted' : 'entry_denied',
      result: rawEvent.result,
      source_brand: 'Salto',
      node_id: rawEvent.door_id,
      user_name: rawEvent.cardholder_name,
      user_role: rawEvent.cardholder_role,
      raw_payload: rawEvent as any,
    };
  } else {
    // Gantner locker event
    return {
      id: rawEvent.event_id,
      credential_id: rawEvent.credential_id,
      location: rawEvent.location,
      timestamp: rawEvent.timestamp,
      event_type: 'locker_action',
      action: rawEvent.action,
      result: rawEvent.result,
      source_brand: 'Gantner',
      node_id: rawEvent.locker_id,
      user_name: 'Session PIN User',
      user_role: 'Locker Occupant',
      raw_payload: rawEvent as any,
    };
  }
}
